// Turns icons.config.json into src/renderer/icons.generated.js, so the app ships only the icons it uses.
//   npm run icons
// Uses Font Awesome Pro when @fortawesome/fontawesome-pro is installed (it needs your Font Awesome npm token),
// and Font Awesome Free otherwise. Icons missing from the chosen style fall back to Solid and are listed.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'icons.config.json'), 'utf8'));

function pkgDir() {
  for (const name of ['@fortawesome/fontawesome-pro', '@fortawesome/fontawesome-free']) {
    try { return { name, dir: path.dirname(require.resolve(name + '/package.json', { paths: [ROOT] })) }; } catch (_) { /* try next */ }
  }
  throw new Error('Install @fortawesome/fontawesome-free (or fontawesome-pro) first.');
}

const { name: pkg, dir } = pkgDir();
const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
const out = {}, fallbacks = [], missing = [];

for (const [key, fa] of Object.entries(cfg.icons)) {
  let style = cfg.style;
  let file = path.join(dir, 'svgs', style, fa + '.svg');
  if (!fs.existsSync(file)) { style = 'solid'; file = path.join(dir, 'svgs', style, fa + '.svg'); if (fs.existsSync(file)) fallbacks.push(`${fa} (not in ${cfg.style})`); }
  if (!fs.existsSync(file)) { missing.push(fa); continue; }
  const svg = fs.readFileSync(file, 'utf8');
  const vb = /viewBox="([^"]+)"/.exec(svg)[1];
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  out[key] = { vb, svg: inner };
}

const label = `${pkg === '@fortawesome/fontawesome-pro' ? 'Font Awesome Pro' : 'Font Awesome Free'} ${version}, ${cfg.style}`;
fs.writeFileSync(path.join(ROOT, 'src/renderer/icons.generated.js'),
  `/* Generated by scripts/build-icons.cjs from ${label}. Do not edit. */\nwindow.FA_SET = ${JSON.stringify(label)};\nwindow.FA_ICONS = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} icons from ${label}`);
if (fallbacks.length) console.log('fell back to solid:', fallbacks.join(', '));
if (missing.length) { console.error('missing:', missing.join(', ')); process.exit(1); }
